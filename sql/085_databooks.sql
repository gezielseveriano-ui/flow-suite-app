-- Arquitetura híbrida (2026-11-06): os certificados/relatórios NÃO sobem pro
-- Supabase -- ficam na pasta do pedido no OneDrive da MDE (uma subpasta por
-- item, como o PR-G-363 pede pro data book eletrônico). Aqui fica só o
-- controle: cabeçalho, revisões e o checklist de itens com o resumo dos
-- arquivos que o programa local (databook_service.py, porta 8010) encontrou
-- na pasta. O PDF final é montado por esse programa, no PC da Qualidade.
--
-- Só pedido que "abriu" data book tem registro aqui (pedido pequeno não
-- precisa) -- um data book por pedido.
-- ============================================================================

create table public.databooks (
  id                    bigint generated always as identity primary key,
  pedido_id             bigint not null unique references public.pedidos(id),

  -- carimbo / capa
  titulo                text not null default 'DATA BOOK',
  projeto               text,              -- ex.: PROJETO CAPANEMA - CT 5500095925 - RETROFIT DO TCLD...
  subtitulo             text,              -- ex.: PROJETO DETALHADO
  numero_cliente        text,              -- Nº Vale (DF-BK-...)
  numero_contratada     text,              -- Nº MDE (T-061278-1)
  revisao               text not null default '0',
  classificacao         text,
  criado_por_nome       text,
  criado_data           date,
  verificado_por_nome   text,
  verificado_data       date,
  aprovado_por_nome     text,
  departamento          text default 'Controle de Qualidade',
  escopo_entregue       text,              -- termo de entrega: data books entregues / TAGs
  numeracao             text not null default 'oficial' check (numeracao in ('oficial', 'sequencial')),
  carimbar_anexos       boolean not null default true,
  capitulos             jsonb not null default '[]'::jsonb,   -- [{num:1, titulo:'...'}]

  -- pasta do pedido no PC da Qualidade (OneDrive), ex.: C:\Users\...\P819 - CAPANEMA\QUALIDADE\DATABOOK
  pasta                 text,

  status                text not null default 'em_montagem' check (status in ('em_montagem', 'gerado', 'enviado', 'aprovado')),
  ultima_geracao        timestamptz,
  ultima_geracao_info   jsonb,             -- {arquivo, paginas, tamanho_mb}

  criado_por            uuid references public.perfis(id) default auth.uid(),
  criado_em             timestamptz not null default now(),
  atualizado_em         timestamptz not null default now()
);

create table public.databook_itens (
  -- "by default": a tela grava a conferência dos arquivos com upsert (id junto)
  id                bigint generated by default as identity primary key,
  databook_id       bigint not null references public.databooks(id) on delete cascade,
  capitulo          smallint not null check (capitulo between 1 and 7),
  codigo            text not null,         -- numeração oficial Vale (4.12) -- também é o nome da subpasta
  descricao         text not null,
  ordem             int not null default 0,
  aplicavel         boolean not null default true,
  origem            text not null default 'pasta' check (origem in ('pasta', 'rnc', 'desenhos')),
  observacao        text,
  -- resumo do que o programa local achou na subpasta do item
  arquivos          jsonb not null default '[]'::jsonb,   -- [{nome, paginas, mb}]
  paginas           int not null default 0,
  conferido_em      timestamptz,
  unique (databook_id, codigo)
);

create index idx_databook_itens_databook on public.databook_itens(databook_id);

create table public.databook_revisoes (
  id            bigint generated always as identity primary key,
  databook_id   bigint not null references public.databooks(id) on delete cascade,
  rev           text not null,
  te            text,            -- tipo de emissão (A..H)
  descricao     text,
  por           text,
  ver           text,
  apr           text,
  aut           text,
  data          date,
  ordem         int not null default 0
);

create index idx_databook_revisoes_databook on public.databook_revisoes(databook_id);

create or replace function public.tocar_atualizado_em_databook()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;

create trigger trg_tocar_atualizado_em_databook
before update on public.databooks
for each row execute function public.tocar_atualizado_em_databook();

